using Argus.Data;
using AutoMapper;
using Argus.Models;
using Argus.Dtos.Auditoriums;
using Argus.Services.Interfaces;
using AutoMapper.QueryableExtensions;
using Microsoft.EntityFrameworkCore;

namespace Argus.Services
{
    public class AuditoriumService(AppDbContext context, IMapper mapper) : IAuditoriumService
    {
        public async Task<List<AuditoriumDto>> GetAllAuditoriumsAsync(CancellationToken ct = default)
        {
            return await context.Auditoriums
                .AsNoTracking()
                .ProjectTo<AuditoriumDto>(mapper.ConfigurationProvider)
                .ToListAsync(ct);
        }

        public async Task<AuditoriumDto?> GetAuditoriumByIdAsync(Guid id, CancellationToken ct = default)
        {
            return await context.Auditoriums
                .AsNoTracking()
                .Where(a => a.Id == id)
                .ProjectTo<AuditoriumDto>( mapper.ConfigurationProvider)
                .FirstOrDefaultAsync(ct);
        }


        public async Task<AuditoriumDto> CreateAuditoriumAsync(CreateAuditoriumDto createAuditoriumDto, CancellationToken ct = default)
        {
            var newAuditorium = mapper.Map<Auditorium>(createAuditoriumDto);
            
            context.Auditoriums.Add(newAuditorium);
            await context.SaveChangesAsync(ct); //The Id is generated by the database and linked to the object

            return mapper.Map <AuditoriumDto>(newAuditorium);
        }

        public async Task<bool> DeleteAuditoriumAsync(Guid id, CancellationToken ct = default)
        {
            var deletedAuditorium = await context.Auditoriums
                .Where(a => a.Id == id)
                .ExecuteDeleteAsync(ct);
            return deletedAuditorium > 0;
        }
    }
}
