using Argus.Data;
using AutoMapper;
using Argus.Models;
using Argus.Dtos.Auditoriums;
using Argus.Services.Interfaces;
using AutoMapper.QueryableExtensions;
using Microsoft.EntityFrameworkCore;
using ErrorOr;
using Argus.Constants.Errors;
using Npgsql;

namespace Argus.Services
{
    public class AuditoriumService(AppDbContext context, IMapper mapper) : IAuditoriumService
    {
        public async Task<List<AuditoriumDto>> GetAllAuditoriumsAsync(CancellationToken ct = default)
        {
            return await context.Auditoriums
                .AsNoTracking()
                .ProjectTo<AuditoriumDto>(mapper.ConfigurationProvider)
                .ToListAsync(ct);
        }

        public async Task<AuditoriumDto?> GetAuditoriumByIdAsync(Guid id, CancellationToken ct = default)
        {
            return await context.Auditoriums
                .AsNoTracking()
                .Where(a => a.Id == id)
                .ProjectTo<AuditoriumDto>( mapper.ConfigurationProvider)
                .FirstOrDefaultAsync(ct);
        }


        public async Task<AuditoriumDto> CreateAuditoriumAsync(CreateAuditoriumDto createAuditoriumDto, CancellationToken ct = default)
        {
            var newAuditorium = mapper.Map<Auditorium>(createAuditoriumDto);
            
            context.Auditoriums.Add(newAuditorium);
            await context.SaveChangesAsync(ct); //The Id is generated by the database and linked to the object

            return mapper.Map <AuditoriumDto>(newAuditorium);
        }

        public async Task<ErrorOr<Success>> DeleteAuditoriumAsync(Guid id, CancellationToken ct = default)
        {
            var auditoriumExists = await context.Auditoriums
                .AnyAsync(a => a.Id == id, ct);

            if(!auditoriumExists)
                return AuditoriumErrors.NotFound;

            var auditoriumInUse = await context.PlacementHistories
                .AnyAsync(ph => ph.AuditoriumId == id, ct);

            if (auditoriumInUse)
                return AuditoriumErrors.InUse;

            var supportRequestInUse = await context.SupportRequests
                .AnyAsync(sr => sr.AuditoriumId == id, ct);
            
            if (supportRequestInUse)
                return AuditoriumErrors.InUse;

            try
            {
                var deletedAuditorium = await context.Auditoriums
                    .Where(a => a.Id == id)
                    .ExecuteDeleteAsync(ct);

                if (deletedAuditorium == 0)
                    return AuditoriumErrors.NotFound;

                return Result.Success;
            }
            catch (PostgresException ex) when(
            (ex.SqlState == PostgresErrorCodes.RestrictViolation ||
            ex.SqlState == PostgresErrorCodes.ForeignKeyViolation)  &&
            (ex.ConstraintName == "fk_placement_histories_auditoriums_auditorium_id" ||
            ex.ConstraintName == "fk_support_requests_auditoriums_auditorium_id"))
            {
                return AuditoriumErrors.InUse;
            }
        }
    }
}
